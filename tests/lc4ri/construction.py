def deployment_cells(controls):
    return dict(certificate=controls.find('use_saml_cert_as_server_cert = False'),
                removal=controls.find('docker stack rm coursewarehub'),
                password=controls.find('db_pass = getpass()'),
                acme=controls.find("acme_server = input('ACME Server URL')\n"
                                   "acme_eab_kid = getpass('ACME EAB KID')\n"
                                   "acme_eab_hmac_key = getpass('ACME HMAC Key')\n"
                                   "acme_email = input('ACME E-mail addrress')\n"
                                   "acme_key_type = input('ACME key type')"))


def deployment_inputs(index, text, controls, cells):
    if index == cells['certificate']:
        controls.edit(index, text.replace('use_saml_cert_as_server_cert = False', 'use_saml_cert_as_server_cert = True'), 'Use the locally provisioned test certificate')
    if index == cells['removal']:
        lines = text.splitlines()
        removed = next(i for i,line in enumerate(lines) if 'docker stack rm coursewarehub' in line)
        wait = """import re
import time
for wait_attempt in range(90):
    remaining_services = !ansible -b -a 'docker service ls --filter label=com.docker.stack.namespace=coursewarehub -q' {target_hub} -l {target_group}
    remaining_containers = !ansible -b -a 'docker ps -q --filter name=coursewarehub_' {target_group}
    removal_status = list(remaining_services) + list(remaining_containers)
    assert not any('FAILED' in line or 'UNREACHABLE' in line for line in removal_status), removal_status
    if not any(re.fullmatch(r'[0-9a-f]{12,64}', line.strip()) for line in remaining_containers) and not any(line.strip() for line in remaining_services[1:]):
        break
    time.sleep(2)
else:
    raise TimeoutError('CoursewareHub services or old containers did not stop')"""
        lines.insert(removed + 1, wait)
        controls.edit(index, '\n'.join(lines), 'Wait for service removal and old containers on every node before redeployment')
    if index == cells['password']:
        return (os.environ['LC4RI_DB_PASSWORD'],)
    if index == cells['acme']:
        return ('', '', '', 'ciadmin@example.test', 'rsa')
    return ()


def inspect_simplesaml_log(notebook, index, controls, master, records):
    observed = controls.run(index, inspect_error=True)
    errors = [o for o in observed['outputs'] if o['output_type'] == 'error']
    path = '/var/www/simplesamlphp/log/simplesamlphp.log'
    if not errors:
        check_output(notebook, index, controls.state(index)['text'], observed)
        return

    streams = ''.join(o['text'] for o in observed['outputs'] if o['output_type'] == 'stream')
    assert len(errors) == 1 and errors[0]['ename'] == 'RuntimeError', errors
    assert f'cat: {path}: No such file or directory' in streams, streams
    logs = remote(master, 'docker service logs --raw coursewarehub_auth-proxy 2>&1')
    assert f'Failed to touch "{path}"' in logs and 'simplesamlphp INFO' in logs, logs
    records.append(dict(notebook=notebook, cell=index, action='read SimpleSAMLphp messages in the service log',
                        file_error=streams))
    print(f'::warning::{notebook} could not read the SimpleSAMLphp file log. Verified SimpleSAMLphp messages in the auth-proxy service log.', flush=True)


