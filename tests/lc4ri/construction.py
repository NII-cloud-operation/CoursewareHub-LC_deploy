def remote(address, command):
    return subprocess.check_output(['ssh', *shlex.split(os.environ['ANSIBLE_SSH_ARGS']),
        'centos@' + address, 'sudo -- ' + command], text=True, timeout=180).strip()


def inventory_cells(original, controls, group):
    inventory = controls.find("hosts_file = './cwhtest0001_inventory'")
    for index, cell in enumerate(original['cells']):
        text = source(cell)
        if cell['cell_type'] != 'code' or not text.strip():
            continue
        if index == inventory and group != 'cwhtest0001':
            controls.edit(index, text.replace('cwhtest0001', group), 'Select the inventory generated by D02')
        yield index, text


def check_output(notebook, index, text, observed):
    output = json.dumps(observed['outputs'], ensure_ascii=False)
    dry_run = '-CD' in text or '-Cv' in text
    if not dry_run and re.search(r'FAILED!|UNREACHABLE!|failed=[1-9]|SQLSTATE\[|psql:[^\n]*ERROR:|ERROR:  relation', output):
        raise AssertionError(f'{notebook} cell {index}: Ansible operation failed: {output[-3000:]}')


def freeze_confirmation(notebook, index, controls, page, records):
    controls.select(index)
    controls.freeze_selected()
    assert controls.state(index)['frozen']
    records.append(dict(notebook=notebook, cell=index, action='confirm prerequisites and Freeze via toolbar'))


