def operate_d02(original, args, controls, page, records, results):
    find, edit, run = controls.find, controls.edit, controls.run
    group_index = find("target_group = 'cwhtest0001'")
    setting = find("nfs_server = '10.1.1.162'\n")
    if setting != find("master_server = '10.1.1.162'"):
        raise ValueError('D02: expected NFS and master selection in the same input cell')
    name = find("hubname = 'cwhtest0001'")
    image = find("group_vars['jupyterhub_image'] = ")
    hostname = find("group_vars['master_fqdn'] = 'example.com'")
    federation = {}
    if args.saml is not None:
        from saml_provider import federation_inputs
        federation = federation_inputs(find, args.saml)
    for index, cell in enumerate(original['cells']):
        text = source(cell)
        if cell['cell_type'] != 'code' or not text.strip():
            continue
        if index in (group_index, name) and args.group != 'cwhtest0001':
            edit(index, text.replace("'cwhtest0001'", repr(args.group)), 'Use the deployment inventory group')
        elif index == setting:
            edit(index, text.replace("'10.1.1.162'", repr(args.master)), 'Select the NFS and master hosts')
        elif index == image and args.hub_image is not None:
            edit(index, re.sub(r"^group_vars\['jupyterhub_image'\] = .+$", "group_vars['jupyterhub_image'] = " + repr(args.hub_image), text, flags=re.M), 'Select the Hub image with the fixture CA')
        elif index == hostname:
            edit(index, text.replace("'example.com'", "'coursewarehub.test'"), 'Set the service hostname')
        elif index in federation:
            old, new = federation[index]
            edit(index, text.replace(old, new), 'Configure the fixture SAML identity provider')
        observed = run(index)
        if index == group_index:
            assert str(observed['outputs']).count('SUCCESS') == 1 + len(args.workers), observed['outputs']


def operate_d03(original, args, controls, page, records, results):
    before = {host: remote(host, 'cat /proc/sys/kernel/random/boot_id') for host in (args.master, *args.workers)}
    for index, text in inventory_cells(original, controls, args.group):
        check_output('D03', index, text, controls.run(index))
    after = {host: remote(host, 'cat /proc/sys/kernel/random/boot_id') for host in before}
    assert before[args.worker] != after[args.worker], 'D03 did not reboot the worker OS'
    mounts = remote(args.worker, 'findmnt --json --target /exchange')
    assert 'nfs' in mounts and args.master in mounts, mounts
    remote(args.master, "sh -c 'echo lc4ri-nfs > /exchange/lc4ri-proof'")
    assert remote(args.worker, 'cat /exchange/lc4ri-proof') == 'lc4ri-nfs'
    (results / 'nfs-reboot.json').write_text(json.dumps(dict(before=before, after=after, mounts=json.loads(mounts)), indent=2))


